export const QUESTIONS: readonly string[] = LOCALE === "en" ? QUESTIONS_EN : QUESTIONS_ES;

const EPOCH_DAY = 19723; // 2024-01-01 in days since 1970

export function questionForDay(dayNumber: number): string {
  const index = (((dayNumber - EPOCH_DAY) % QUESTIONS.length) + QUESTIONS.length) % QUESTIONS.length;
  return QUESTIONS[index] as string;
}
