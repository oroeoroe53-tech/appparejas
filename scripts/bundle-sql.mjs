// Concatenates the migrations that come AFTER 20260102 into one file you can paste in the Supabase SQL editor
// (for projects that already applied init + old_letter_and_song). Run: npm run sql:bundle
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase");
const FROM = "20260103000000";
const files = (await readdir(join(root, "migrations"))).filter((f) => f.endsWith(".sql") && f.slice(0, 14) >= FROM).sort();
let out = `-- US: everything added after the Old Letter / song migration.\n-- Generated by "npm run sql:bundle" from supabase/migrations. Safe to paste into the Supabase SQL editor.\n-- Wrapped in a transaction: if anything fails, nothing is applied.\n\nbegin;\n\n`;
for (const f of files) out += `-- ===== ${f} =====\n\n${(await readFile(join(root, "migrations", f), "utf8")).trim()}\n\n`;
out += "commit;\n";
await writeFile(join(root, "bundles", "after-02.sql"), out);
console.log(`bundled ${files.length} migrations:`, files.join(", "));
